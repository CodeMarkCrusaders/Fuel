"""
fuel_equilibrium.rocket.signal_cleanup
=======================================

Подавление численного шума в профилях параметров газа по оси сопла.

Параметры течения в сопле физически МОНОТОННЫ по ходу потока
(P, T, ρ убывают от камеры к срезу; V, M — растут). Решатель равновесия
(SP-задача) в отдельных сечениях иногда не сходится до конца и даёт
одиночные «иголки»/«резкие пики», выбивающиеся из монотонного тренда.

Здесь собраны «чистые» (без зависимостей от GUI) функции их подавления:

  * :func:`pava_increasing` — изотоническая регрессия (Pool Adjacent
    Violators), ближайшая НЕубывающая кривая к данным, O(n);
  * :func:`monotone_despike` — удаление выбросов из монотонной величины по
    отклонению от изотонической оценки;
  * :func:`hampel_filter` — мягкий медианный фильтр для НЕмонотонных гладких
    величин (γₛ, скорость звука).

Все функции работают с одномерными numpy-массивами и не меняют вход на месте.
"""

from __future__ import annotations

import numpy as np


__all__ = ["pava_increasing", "monotone_despike", "hampel_filter"]


def pava_increasing(z) -> np.ndarray:
    """Изотоническая регрессия (PAVA) — ближайшая НЕубывающая кривая к ``z``.

    Pool-Adjacent-Violators algorithm, сложность O(n). Возвращает массив той же
    длины, что и ``z``, с неубывающими значениями (взвешенные средние слитых
    блоков-нарушителей). Используется как эталон монотонного тренда.
    """
    z = np.asarray(z, dtype=float)
    n = z.size
    vals: list[float] = []
    wts: list[float] = []
    szs: list[int] = []
    for i in range(n):
        v = float(z[i])
        ww = 1.0
        sz = 1
        while vals and vals[-1] > v + 1e-15:
            pv = vals.pop()
            pw = wts.pop()
            ps = szs.pop()
            v = (pv * pw + v * ww) / (pw + ww)
            ww = pw + ww
            sz = ps + sz
        vals.append(v)
        wts.append(ww)
        szs.append(sz)
    fit = np.empty(n, dtype=float)
    idx = 0
    for v, sz in zip(vals, szs):
        fit[idx:idx + sz] = v
        idx += sz
    return fit


def monotone_despike(y, decreasing: bool = True,
                     rel_tol: float = 0.03, iters: int = 8,
                     curv_k: float = 2.0) -> np.ndarray:
    """Подавляет «резкие пики» в МОНОТОННОЙ по ходу потока величине.

    Выброс детектируется ТРЕМЯ независимыми способами (берётся объединение):

      1. отклонение от изотонической регрессии (PAVA) больше
         ``rel_tol``·(размах тренда) — ловит крупные сдвиги;
      2. локальное нарушение монотонности — точка-«зубец», которая выше (или
         ниже) ОБОИХ соседей больше чем на ``rel_tol``·размах. Это ловит
         одиночные «иголки», которые PAVA «всасывает» в блок и потому сам по
         себе не отмечает;
      3. большая кривизна — модуль второй разности |yᵢ₋₁ − 2yᵢ + yᵢ₊₁|
         превышает ``curv_k``·tol. Это напрямую ловит «резкие пики» (именно их
         измеряет показатель «пиковости» = max|2-я разность|/размах) и, в
         отличие от пунктов 1–2, срабатывает даже на СОСЕДНИХ выбросах
         (кластерах из 2–3 испорченных точек подряд), которые изотоническая
         оценка и «зубцовый» тест пропускают.

    Отмеченные точки заменяются линейной интерполяцией по «хорошим» соседям.
    Процедура итеративная (``iters`` проходов добивают близко стоящие выбросы),
    после чего остаточные отклонения проецируются на изотоническую оценку.
    На гладком монотонном профиле (даже с физическим джиттером) правки нулевые.

    Параметры
    ---------
    y : array-like
        Профиль величины вдоль оси (отсортированный по координате потока).
    decreasing : bool
        True — величина убывает по ходу потока (P, T, ρ, H);
        False — растёт (V, M).
    rel_tol : float
        Порог отклонения от тренда в долях размаха изотонической оценки.
    iters : int
        Число итераций чистки.
    curv_k : float
        Множитель порога для критерия кривизны (п. 3 выше): точка считается
        «резким пиком», если |2-я разность| > ``curv_k``·``rel_tol``·размах.
        ``2.0`` — компромисс: убирает пики (в т.ч. соседние), не трогая
        физический джиттер гладкого профиля.

    Возвращает новый массив; вход не изменяется.
    """
    y = np.asarray(y, dtype=float).copy()
    n = y.size
    if n < 4:
        return y
    if np.isfinite(y).sum() < 4:
        return y
    s = -1.0 if decreasing else 1.0
    xi = np.arange(n)
    for _ in range(int(max(1, iters))):
        # работаем в «неубывающем» представлении z = s·y
        z = s * y
        iso = pava_increasing(z)
        span = float(np.nanmax(iso) - np.nanmin(iso)) + 1e-12
        tol = rel_tol * span

        # (1) отклонение от изотонической оценки
        bad = np.abs(z - iso) > tol

        if n >= 3:
            up = z[1:-1] - z[:-2]      # разность с левым соседом
            dn = z[1:-1] - z[2:]       # разность с правым соседом
            # (2) локальные «зубцы»: точка выше/ниже ОБОИХ соседей больше tol
            peak = (up > tol) & (dn > tol)        # пик (выше обоих)
            dip = (-up > tol) & (-dn > tol)       # провал (ниже обоих)
            bad[1:-1] |= (peak | dip)
            # (3) большая кривизна — |2-я разность| > curv_k·tol. Ловит «резкие
            # пики» напрямую и срабатывает даже на СОСЕДНИХ выбросах, которые
            # изотоническая оценка «всасывает» в общий блок.
            d2 = np.abs(z[:-2] - 2.0 * z[1:-1] + z[2:])
            bad[1:-1] |= d2 > curv_k * tol

        if not bad.any():
            break
        good = ~bad
        if good.sum() < 2:
            break
        y[bad] = np.interp(xi[bad], xi[good], y[good])

    # Финальная страховка: остаточные отклонения от монотонного тренда
    # проецируются на изотоническую оценку (строго монотонную). Проход
    # повторяется до стабилизации, чтобы добить кластеры соседних выбросов.
    # На чистых данных отклонение от изотонической оценки нулевое — правок нет.
    for _ in range(6):
        z = s * y
        iso = pava_increasing(z)
        span = float(np.nanmax(iso) - np.nanmin(iso)) + 1e-12
        resid = np.abs(z - iso) > rel_tol * span
        if not resid.any():
            break
        y = s * np.where(resid, iso, z)
    return y


def hampel_filter(y, window: int = 2, n_sigma: float = 3.0) -> np.ndarray:
    """Медианный фильтр Хампеля — для НЕмонотонных гладких величин.

    Точка считается выбросом, если отклоняется от скользящей медианы более чем
    на ``n_sigma``·(1.4826·MAD), и заменяется этой медианой. Сохраняет плавный
    физический тренд, убирая одиночные «иголки» (γₛ, скорость звука).

    Возвращает новый массив; вход не изменяется.
    """
    y = np.asarray(y, dtype=float)
    n = y.size
    if n < 2 * window + 1:
        return y.copy()
    out = y.copy()
    for i in range(n):
        lo = max(0, i - window)
        hi = min(n, i + window + 1)
        seg = y[lo:hi]
        med = np.median(seg)
        mad = np.median(np.abs(seg - med))
        sigma = 1.4826 * mad
        if sigma > 0 and abs(y[i] - med) > n_sigma * sigma:
            out[i] = med
    return out
